# ------------------------------------------------------------------------------
# Hentikan Semua Layanan (Stop)
# ------------------------------------------------------------------------------
stop_services() {
    log_info "Menghentikan seluruh layanan Quake3-Azure..."
    
    for svc in website server master; do
        if [ -f "$RUN_DIR/$svc.pid" ]; then
            local pid
            pid=$(cat "$RUN_DIR/$svc.pid")
            if kill -0 "$pid" 2>/dev/null; then
                kill "$pid" 2>/dev/null || true
            fi
            rm -f "$RUN_DIR/$svc.pid"
        fi
    done

    pkill -f "ioq3ded" 2>/dev/null || true
    pkill -f "game/server/dist/app/main.mjs" 2>/dev/null || true
    pkill -f "quarkus-run.jar" 2>/dev/null || true

    docker compose down 2>/dev/null || docker compose stop 2>/dev/null || true
    log_success "Semua layanan telah dihentikan."
}

# ------------------------------------------------------------------------------
# Status Layanan
# ------------------------------------------------------------------------------
check_status() {
    echo ""
    echo -e "${CYAN}=== Status Layanan Quake3-Azure ===${NC}"

    if docker compose ps database 2>/dev/null | grep -q "Up"; then
        echo -e "  [PostgreSQL Database]    : ${GREEN}AKTIF (Port 5432)${NC}"
    else
        echo -e "  [PostgreSQL Database]    : ${RED}MATI${NC}"
    fi

    if curl -sf http://127.0.0.1:8081/healthz >/dev/null 2>&1; then
        echo -e "  [Static Asset Server]    : ${GREEN}AKTIF (Port 8081)${NC}"
    else
        echo -e "  [Static Asset Server]    : ${RED}MATI${NC}"
    fi

    if curl -sf http://127.0.0.1:8080/api/status >/dev/null 2>&1; then
        echo -e "  [Master Server API]      : ${GREEN}AKTIF (Port 8080)${NC}"
    else
        echo -e "  [Master Server API]      : ${RED}MATI${NC}"
    fi

    if curl -sf http://127.0.0.1:27961/healthz >/dev/null 2>&1; then
        echo -e "  [Game Server & Gateway]  : ${GREEN}AKTIF (Port 27961/27960)${NC}"
    else
        echo -e "  [Game Server & Gateway]  : ${RED}MATI${NC}"
    fi

    if timeout 1 bash -c "cat < /dev/null > /dev/tcp/127.0.0.1/3000" 2>/dev/null; then
        echo -e "  [Website Frontend]       : ${GREEN}AKTIF (Port 3000)${NC}"
    else
        echo -e "  [Website Frontend]       : ${RED}MATI${NC}"
    fi
    echo ""
}

# ------------------------------------------------------------------------------
# Monitoring Foreground Loop
# ------------------------------------------------------------------------------
run_interactive_foreground() {
    show_dashboard
    trap 'echo ""; log_info "Menutup semua layanan..."; stop_services; exit 0' INT TERM EXIT

    echo -e "${YELLOW}Ketik perintah:${NC}"
    echo -e "  ${WHITE}[s]${NC} Status     ${WHITE}[l]${NC} Logs     ${WHITE}[q]${NC} Keluar"
    echo ""

    while true; do
        if read -r -t 2 input 2>/dev/null; then
            case "$input" in
                s|status|S) check_status ;;
                l|log|logs|L)
                    tail -n 10 "$LOGS_DIR/website.log" 2>/dev/null || true
                    tail -n 10 "$LOGS_DIR/server.log" 2>/dev/null || true
                    tail -n 10 "$LOGS_DIR/master.log" 2>/dev/null || true
                    ;;
                q|quit|exit|Q)
                    stop_services
                    trap - INT TERM EXIT
                    exit 0
                    ;;
            esac
        fi
    done
}

# ------------------------------------------------------------------------------
# Main Entry Point & Argument Parsing
# ------------------------------------------------------------------------------
COMMAND="run"
CUSTOM_IP=""
USE_DEV_MODE=false
IS_PROD=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        run|start|stop|restart|status|logs|help) COMMAND="$1"; shift ;;
        --daemon|-d) COMMAND="start"; shift ;;
        --ip) CUSTOM_IP="$2"; shift 2 ;;
        --dev) USE_DEV_MODE=true; shift ;;
        --prod) IS_PROD=true; shift ;;
        --clean) rm -rf "$LOGS_DIR" "$RUN_DIR"; mkdir -p "$LOGS_DIR" "$RUN_DIR"; shift ;;
        -h|--help) show_help; exit 0 ;;
        *) log_error "Opsi tidak dikenal: $1"; exit 1 ;;
    esac
done

case "$COMMAND" in
    stop) stop_services; exit 0 ;;
    status) check_status; exit 0 ;;
    restart) stop_services; sleep 2; COMMAND="run" ;;
esac

# Otomatisasi Penentuan Host IP
if [ -n "$CUSTOM_IP" ]; then
    HOST_IP="$CUSTOM_IP"
else
    HOST_IP=$(detect_host_ip)
fi
export HOST_IP

check_prerequisites
sync_environment "$HOST_IP"

start_docker_services
start_master_server "$USE_DEV_MODE"
start_game_server
start_website "$IS_PROD"

if [ "$COMMAND" = "start" ]; then
    show_dashboard
    log_success "Berjalan di background (daemon mode)."
    exit 0
else
    run_interactive_foreground
fi