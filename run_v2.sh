# ------------------------------------------------------------------------------
# Hentikan Semua Layanan (Stop)
# ------------------------------------------------------------------------------
stop_services() {
    log_info "Menghentikan seluruh layanan Quake3-Azure..."

    # 1. Matikan Website
    if [ -f "$RUN_DIR/website.pid" ]; then
        local pid
        pid=$(cat "$RUN_DIR/website.pid")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Menghentikan Website (PID: $pid)..."
            kill "$pid" 2>/dev/null || true
        fi
        rm -f "$RUN_DIR/website.pid"
    fi

    # 2. Matikan Game Server
    if [ -f "$RUN_DIR/server.pid" ]; then
        local pid
        pid=$(cat "$RUN_DIR/server.pid")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Menghentikan Game Server & Gateway (PID: $pid)..."
            kill "$pid" 2>/dev/null || true
        fi
        rm -f "$RUN_DIR/server.pid"
    fi

    # 3. Matikan Master Server
    if [ -f "$RUN_DIR/master.pid" ]; then
        local pid
        pid=$(cat "$RUN_DIR/master.pid")
        if kill -0 "$pid" 2>/dev/null; then
            log_info "Menghentikan Master Server (PID: $pid)..."
            kill "$pid" 2>/dev/null || true
        fi
        rm -f "$RUN_DIR/master.pid"
    fi

    # Bersihkan sisa proses anak jika ada (ioq3ded, quarkus, next)
    pkill -f "ioq3ded" 2>/dev/null || true
    pkill -f "game/server/dist/app/main.mjs" 2>/dev/null || true
    pkill -f "quarkus-run.jar" 2>/dev/null || true

    # 4. Hentikan Docker containers
    log_info "Menghentikan container Docker..."
    docker compose down 2>/dev/null || docker compose stop 2>/dev/null || true

    log_success "Semua layanan Quake3-Azure telah berhasil dihentikan."
}

# ------------------------------------------------------------------------------
# Periksa Status Layanan (Status)
# ------------------------------------------------------------------------------
check_status() {
    echo ""
    echo -e "${CYAN}=== Status Layanan Quake3-Azure ===${NC}"

    # Database
    if docker compose ps database 2>/dev/null | grep -q "Up"; then
        echo -e "  [PostgreSQL Database]    : ${GREEN}AKTIF (Docker, Port 5432)${NC}"
    else
        echo -e "  [PostgreSQL Database]    : ${RED}MATI${NC}"
    fi

    # Static
    if curl -sf http://127.0.0.1:8081/healthz >/dev/null 2>&1; then
        echo -e "  [Static Asset Server]    : ${GREEN}AKTIF (Port 8081 - HTTP 200 OK)${NC}"
    else
        echo -e "  [Static Asset Server]    : ${RED}MATI${NC}"
    fi

    # Master
    if curl -sf http://127.0.0.1:8080/api/status >/dev/null 2>&1; then
        echo -e "  [Master Server API]      : ${GREEN}AKTIF (Port 8080 - HTTP 200 OK)${NC}"
    else
        echo -e "  [Master Server API]      : ${RED}MATI${NC}"
    fi

    # Game Gateway
    if curl -sf http://127.0.0.1:27961/healthz >/dev/null 2>&1; then
        echo -e "  [Game Server & Gateway]  : ${GREEN}AKTIF (Port 27961 WS, 27960 UDP)${NC}"
    else
        echo -e "  [Game Server & Gateway]  : ${RED}MATI${NC}"
    fi

    # Website
    if timeout 1 bash -c "cat < /dev/null > /dev/tcp/127.0.0.1/3000" 2>/dev/null; then
        echo -e "  [Website Frontend]       : ${GREEN}AKTIF (Port 3000)${NC}"
    else
        echo -e "  [Website Frontend]       : ${RED}MATI${NC}"
    fi
    echo ""
}

# ------------------------------------------------------------------------------
# Monitoring Foreground Loop (Ctrl+C Trapping)
# ------------------------------------------------------------------------------
run_interactive_foreground() {
    show_dashboard

    # Trap Ctrl+C (SIGINT) dan SIGTERM untuk shutdown bersih
    trap 'echo ""; log_info "Sinyal interupsi diterima (Ctrl+C). Menutup semua layanan..."; stop_services; exit 0' INT TERM EXIT

    echo -e "${YELLOW}Ketik perintah:${NC}"
    echo -e "  ${WHITE}[s]${NC} Periksa Status     ${WHITE}[l]${NC} Tampilkan Log Terkini"
    echo -e "  ${WHITE}[q]${NC} Keluar & Hentikan Layanan"
    echo -e "${BLUE}[INFO] Tekan ${BOLD}Ctrl+C${NC}${BLUE} kapan saja untuk keluar dan mematikan semua layanan.${NC}"
    echo ""

    while true; do
        if read -r -t 2 input 2>/dev/null; then
            case "$input" in
                s|status|S)
                    check_status
                    ;;
                l|log|logs|L)
                    echo -e "${CYAN}--- 10 Baris Log Terakhir Website ---${NC}"
                    tail -n 10 "$LOGS_DIR/website.log" 2>/dev/null || true
                    echo -e "${CYAN}--- 10 Baris Log Terakhir Game Server ---${NC}"
                    tail -n 10 "$LOGS_DIR/server.log" 2>/dev/null || true
                    echo -e "${CYAN}--- 10 Baris Log Terakhir Master Server ---${NC}"
                    tail -n 10 "$LOGS_DIR/master.log" 2>/dev/null || true
                    ;;
                q|quit|exit|Q)
                    log_info "Permintaan keluar diterima. Mematikan seluruh layanan..."
                    stop_services
                    trap - INT TERM EXIT
                    exit 0
                    ;;
            esac
        fi

        # Cek apakah salah satu process crash di latar belakang
        for svc in website server master; do
            if [ -f "$RUN_DIR/$svc.pid" ]; then
                local pid
                pid=$(cat "$RUN_DIR/$svc.pid")
                if ! kill -0 "$pid" 2>/dev/null; then
                    log_warn "Layanan $svc terhenti tidak terduga! Lihat logs/$svc.log."
                fi
            fi
        done
    done
}

# ------------------------------------------------------------------------------
# Log Viewer
# ------------------------------------------------------------------------------
show_logs() {
    local target="${1:-all}"
    case "$target" in
        website|web|frontend)
            tail -f "$LOGS_DIR/website.log"
            ;;
        master|api)
            tail -f "$LOGS_DIR/master.log"
            ;;
        server|game)
            tail -f "$LOGS_DIR/server.log"
            ;;
        static)
            docker compose logs -f static
            ;;
        database|db)
            docker compose logs -f database
            ;;
        all|*)
            log_info "Menampilkan live log (Tekan Ctrl+C untuk keluar)..."
            tail -f "$LOGS_DIR/website.log" "$LOGS_DIR/server.log" "$LOGS_DIR/master.log" 2>/dev/null
            ;;
    esac
}

# ------------------------------------------------------------------------------
# Main Entry Point & Argument Parsing
# ------------------------------------------------------------------------------
COMMAND="run"
CUSTOM_IP=""
USE_DEV_MODE=false
IS_PROD=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        run|start|stop|restart|status|logs|help)
            COMMAND="$1"
            shift
            ;;
        --daemon|-d)
            COMMAND="start"
            shift
            ;;
        --ip)
            CUSTOM_IP="$2"
            shift 2
            ;;
        --dev)
            USE_DEV_MODE=true
            shift
            ;;
        --prod)
            IS_PROD=true
            shift
            ;;
        --clean)
            rm -rf "$LOGS_DIR" "$RUN_DIR"
            mkdir -p "$LOGS_DIR" "$RUN_DIR"
            shift
            ;;
        -h|--help)
            show_help
            exit 0
            ;;
        *)
            log_error "Opsi tidak dikenal: $1"
            show_help
            exit 1
            ;;
    esac
done

case "$COMMAND" in
    help)
        show_help
        exit 0
        ;;
    stop)
        stop_services
        exit 0
        ;;
    status)
        check_status
        exit 0
        ;;
    logs)
        show_logs "${1:-all}"
        exit 0
        ;;
    restart)
        log_info "Melakukan restart seluruh layanan..."
        stop_services
        sleep 2
        COMMAND="run"
        ;;
esac

# Tentukan Host IP
if [ -n "$CUSTOM_IP" ]; then
    HOST_IP="$CUSTOM_IP"
else
    HOST_IP=$(detect_host_ip)
fi
export HOST_IP

check_prerequisites
sync_environment "$HOST_IP"

