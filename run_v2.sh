# ------------------------------------------------------------------------------
# Deteksi Host IP (Localhost / LAN / Azure VM Public IP)
# ------------------------------------------------------------------------------
detect_host_ip() {
    if [ -n "${SERVER_IP:-}" ]; then
        echo "$SERVER_IP"
        return
    fi

    # 1. Coba Azure Instance Metadata Service (IMDS)
    local azure_ip=""
    azure_ip=$(curl -s -m 1 -H Metadata:true "http://169.254.169.254/metadata/instance/network/interface/0/ipv4/ipAddress/0/publicIpAddress?api-version=2021-02-01&format=text" 2>/dev/null || true)
    if [ -n "$azure_ip" ] && [[ "$azure_ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        echo "$azure_ip"
        return
    fi

    # 2. Default untuk pengujian lokal
    echo "localhost"
}

# ------------------------------------------------------------------------------
# Sinkronisasi Konfigurasi Environment (website/.env.local)
# ------------------------------------------------------------------------------
sync_environment() {
    local host_ip="$1"
    local env_file="$PROJECT_ROOT/website/.env.local"

    log_info "Menyiapkan environment website/.env.local (Host Target: $host_ip)..."

    cat << EOF > "$env_file"
# Auto-generated by run.sh for Quake3-Azure
NEXT_PUBLIC_Q3JS_MASTER_URL=http://${host_ip}:8080
Q3JS_MASTER_URL=http://127.0.0.1:8080
NEXT_PUBLIC_Q3JS_STATIC_URL=http://${host_ip}:8081
NEXT_PUBLIC_Q3JS_SITE_URL=http://${host_ip}:3000
NEXT_PUBLIC_GA_MEASUREMENT_ID=G-1234567890
EOF

    echo "$host_ip" > "$RUN_DIR/host_ip"
    log_success "Konfigurasi website/.env.local disinkronkan."
}

# ------------------------------------------------------------------------------
# Verifikasi Prasyarat
# ------------------------------------------------------------------------------
check_prerequisites() {
    log_info "Memeriksa kesiapan prasyarat sistem..."

    # Docker
    if ! command -v docker >/dev/null 2>&1; then
        log_error "Docker tidak ditemukan. Harap pasang Docker terlebih dahulu (atau jalankan ./setup-ubuntu.sh)."
        exit 1
    fi

    if ! docker info >/dev/null 2>&1; then
        log_error "Docker daemon tidak berjalan atau izin user belum aktif. Coba jalankan: sudo systemctl start docker"
        exit 1
    fi

    # Node.js
    if ! command -v node >/dev/null 2>&1; then
        log_error "Node.js tidak ditemukan. Pasang Node.js 20+ atau jalankan ./setup-ubuntu.sh."
        exit 1
    fi

    # pnpm
    if ! command -v pnpm >/dev/null 2>&1; then
        log_error "pnpm tidak ditemukan. Pasang via 'npm i -g pnpm' atau jalankan ./setup-ubuntu.sh."
        exit 1
    fi

    # Java
    if ! command -v java >/dev/null 2>&1; then
        log_error "Java runtime tidak ditemukan. Pasang OpenJDK 17+ atau jalankan ./setup-ubuntu.sh."
        exit 1
    fi

    # Quake 3 Data
    if [ ! -f "$PROJECT_ROOT/Q3A/baseq3/pak0.pk3" ]; then
        log_warn "File 'quake3-data/baseq3/pak0.pk3' tidak terdeteksi!"
        log_warn "Game client dan server memerlukan data game asli Quake 3 Arena agar dapat dimainkan."
    fi

    # Build server check
    if [ ! -f "$PROJECT_ROOT/game/server/dist/app/main.mjs" ]; then
        log_info "Game server belum di-build. Menjalankan game/server/build.sh..."
        ./game/server/build.sh
    fi
}

# ------------------------------------------------------------------------------
# Fungsi Helper Menunggu Port / Endpoint HTTP
# ------------------------------------------------------------------------------
wait_for_url() {
    local url="$1"
    local name="$2"
    local max_wait="${3:-30}"
    local count=0

    printf "${CYAN}[WAIT]${NC} Menunggu %s siap di %s..." "$name" "$url"
    while [ $count -lt "$max_wait" ]; do
        if curl -sf --max-time 1 "$url" >/dev/null 2>&1; then
            printf " ${GREEN}[SIAP]${NC}\n"
            return 0
        fi
        sleep 1
        count=$((count + 1))
        printf "."
    done

    printf " ${YELLOW}[TIMEOUT]${NC}\n"
    log_warn "$name membutuhkan waktu lebih lama dari biasanya untuk merespons ($url)."
    return 1
}

wait_for_port() {
    local host="$1"
    local port="$2"
    local name="$3"
    local max_wait="${4:-25}"
    local count=0

    printf "${CYAN}[WAIT]${NC} Menunggu port %s (%s)..." "$port" "$name"
    while [ $count -lt "$max_wait" ]; do
        if timeout 1 bash -c "cat < /dev/null > /dev/tcp/$host/$port" 2>/dev/null; then
            printf " ${GREEN}[SIAP]${NC}\n"
            return 0
        fi
        sleep 1
        count=$((count + 1))
        printf "."
    done

    printf " ${YELLOW}[TIMEOUT]${NC}\n"
    return 1
}

# ------------------------------------------------------------------------------
# 1. Start Database & Static Server (Docker Compose)
# ------------------------------------------------------------------------------
start_docker_services() {
    log_info "Menjalankan container Docker (PostgreSQL & Static Asset Server)..."
    docker compose up -d

    # Tunggu database siap
    local retries=15
    while [ $retries -gt 0 ]; do
        if docker compose exec -T database pg_isready -U postgres -d postgres >/dev/null 2>&1; then
            log_success "Database PostgreSQL 17 siap pada port 5432."
            break
        fi
        sleep 1
        retries=$((retries - 1))
    done

    # Tunggu static asset server
    wait_for_url "http://127.0.0.1:8081/healthz" "Static Asset Server (Nginx)" 15 || true
}

# ------------------------------------------------------------------------------
# 2. Start Master Server (Quarkus)
# ------------------------------------------------------------------------------
start_master_server() {
    local use_dev_mode="$1"

    # Periksa apakah master server sudah berjalan
    if [ -f "$RUN_DIR/master.pid" ] && kill -0 "$(cat "$RUN_DIR/master.pid")" 2>/dev/null; then
        log_warn "Master Server API sudah berjalan (PID: $(cat "$RUN_DIR/master.pid"))."
        return
    fi

    log_info "Menjalankan Master Server API (Quarkus Port 8080)..."

    # --- Auto-generate JWT RSA keypair jika belum ada ---
    local private_key="$RUN_DIR/privateKey.pem"
    local public_key="$RUN_DIR/publicKey.pem"
    if [ ! -f "$private_key" ] || [ ! -f "$public_key" ]; then
        log_info "Membuat JWT RSA keypair untuk admin auth di .run/ ..."
        openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$private_key" 2>/dev/null
        openssl pkey -in "$private_key" -pubout -out "$public_key" 2>/dev/null
        log_success "JWT keypair dibuat: .run/privateKey.pem & .run/publicKey.pem"
    fi

    export Q3JS_ADMIN_PASSWORD="${Q3JS_ADMIN_PASSWORD:-admin12345}"
    export Q3JS_EVENT_CLIENT_SECRET="${Q3JS_EVENT_CLIENT_SECRET:-98e9b63a7b1bcd9103cdc951cda26976d06b6076df6ab13da1f20c25c7699167}"
    export Q3JS_LIVEKIT_API_KEY="${Q3JS_LIVEKIT_API_KEY:-devkey}"
    export Q3JS_LIVEKIT_API_SECRET="${Q3JS_LIVEKIT_API_SECRET:-devsecretdevsecretdevsecretdevsecret}"
    export Q3JS_LIVEKIT_URL="${Q3JS_LIVEKIT_URL:-https://staging.livekit.q3js.com}"
    export Q3JS_CORS_ORIGINS="/.*/"
    export QUARKUS_HTTP_CORS=true
    export QUARKUS_HTTP_CORS_ORIGINS="/.*/"
    export Q3JS_ADMIN_JWT_PRIVATE_KEY_LOCATION="$private_key"
    export Q3JS_ADMIN_JWT_PUBLIC_KEY_LOCATION="$public_key"
    export QUARKUS_TEST_CONTINUOUS_TESTING=disabled
    export QUARKUS_CONSOLE_ENABLED=false
    export QUARKUS_HTTP_TEST_PORT=8082
    export QUARKUS_HTTP_HOST=0.0.0.0

    if [ "$use_dev_mode" = false ] && [ -f "$PROJECT_ROOT/master/target/quarkus-app/quarkus-run.jar" ]; then
        log_info "Menggunakan binary quarkus-run.jar (Fast Start)..."
        # Jalankan dari direktori master/ agar relative path default config terpenuhi
        # nohup + disown agar proses tetap hidup setelah shell exit (daemon mode)
        ( cd "$PROJECT_ROOT/master" && nohup java -jar target/quarkus-app/quarkus-run.jar >> "$LOGS_DIR/master.log" 2>&1 & echo $! ) > "$RUN_DIR/master.pid"
    else
        log_info "Menjalankan via Maven dev mode (mvnw quarkus:dev)..."
        ( cd "$PROJECT_ROOT/master" && nohup ./mvnw quarkus:dev >> "$LOGS_DIR/master.log" 2>&1 & echo $! ) > "$RUN_DIR/master.pid"
    fi

    # Tunggu sampai server merespons /api/status (lebih stabil dari /q/health)
    wait_for_url "http://127.0.0.1:8080/api/status" "Master Server API" 45 || true
    log_success "Master Server API aktif."
}

# ------------------------------------------------------------------------------
# 3. Start Game Server & Gateway
# ------------------------------------------------------------------------------
start_game_server() {
    if [ -f "$RUN_DIR/server.pid" ] && kill -0 "$(cat "$RUN_DIR/server.pid")" 2>/dev/null; then
        log_warn "Game Server sudah berjalan (PID: $(cat "$RUN_DIR/server.pid"))."
        return
    fi

    log_info "Menjalankan Game Dedicated Server (ioq3ded) & Gateway (Port 27961)..."

    export Q3JS_BASEPATH="${Q3JS_BASEPATH:-$PROJECT_ROOT/Q3A}"
    export Q3JS_PUBLISH_HOST="${HOST_IP:-localhost}"
    export Q3JS_MASTER_URL="http://localhost:8080"

    # nohup + subshell agar proses tetap hidup setelah shell exit
    ( nohup node "$PROJECT_ROOT/game/server/dist/app/main.mjs" >> "$LOGS_DIR/server.log" 2>&1 & echo $! ) > "$RUN_DIR/server.pid"

    wait_for_url "http://127.0.0.1:27961/healthz" "Game Gateway WebSocket" 20 || true
    log_success "Game Server ioquake3 & Gateway aktif."
}

# ------------------------------------------------------------------------------
# 4. Start Website (Next.js)
# ------------------------------------------------------------------------------
start_website() {
    local is_prod="$1"

    if [ -f "$RUN_DIR/website.pid" ] && kill -0 "$(cat "$RUN_DIR/website.pid")" 2>/dev/null; then
        log_warn "Website Frontend sudah berjalan (PID: $(cat "$RUN_DIR/website.pid"))."
        return
    fi

    log_info "Menjalankan Website Frontend (Next.js Port 3000)..."

    if [ "$is_prod" = true ] && [ -d "$PROJECT_ROOT/website/.next" ]; then
        log_info "Mode Produksi: pnpm --dir website start..."
        ( cd "$PROJECT_ROOT/website" && PORT=3000 HOSTNAME=0.0.0.0 nohup node .next/standalone/website/server.js >> "$LOGS_DIR/website.log" 2>&1 & echo $! ) > "$RUN_DIR/website.pid"
    else
        log_info "Mode Dev (Turbopack): pnpm --dir website dev..."
        ( cd "$PROJECT_ROOT" && nohup pnpm --dir website dev -H 0.0.0.0 >> "$LOGS_DIR/website.log" 2>&1 & echo $! ) > "$RUN_DIR/website.pid"
    fi

    wait_for_port "127.0.0.1" 3000 "Website Frontend" 25 || true
    log_success "Website Frontend aktif."
}

