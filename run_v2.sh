#!/usr/bin/env bash
# ==============================================================================
# Script All-in-One Launcher untuk Quake3-Azure (Q3JS)
# Menjalankan seluruh layanan dengan 1 klik / 1 perintah:
# 1. PostgreSQL Database (Docker)
# 2. Static Asset Server (Docker - Port 8081)
# 3. Master Server API (Quarkus Java 17 - Port 8080)
# 4. Game Dedicated Server & WebSocket Gateway (ioq3ded + Node - Port 27960/27961)
# 5. Website Frontend (Next.js - Port 3000)
# ==============================================================================

set -Eeuo pipefail

# ANSI color codes
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
CYAN='\033[0;36m'
WHITE='\033[1;37m'
BOLD='\033[1m'
NC='\033[0m' # No Color

PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_ROOT"

RUN_DIR="$PROJECT_ROOT/.run"
LOGS_DIR="$PROJECT_ROOT/logs"

mkdir -p "$RUN_DIR" "$LOGS_DIR"

log_info() {
    printf "${BLUE}[INFO]${NC} %s\n" "$1"
}

log_success() {
    printf "${GREEN}[SUCCESS]${NC} %s\n" "$1"
}

log_warn() {
    printf "${YELLOW}[WARN]${NC} %s\n" "$1"
}

log_error() {
    printf "${RED}[ERROR]${NC} %s\n" "$1" >&2
}

